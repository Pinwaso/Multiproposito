package Clase.Examenes.William;

public class Profesor extends Persona {
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////VARIABLES ///////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private String especialidad;
	private double salarioBase;
////////////////////////////////////////////////////////////////////////////////
///////////////////////////////// CONSTRUCTOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public Profesor(String id, String nombre, int edad, String dni, String especialidad, double salarioBase)
			throws EdadInvalidaException {
		super(id, nombre, edad, dni);
		this.especialidad = especialidad;
		this.salarioBase = salarioBase;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// METODOS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	@Override
	public String mostrarIdentificacion() {
		return "Profesor " + super.toString() + ", especialidad=" + especialidad + ", salarioBase=" + salarioBase + "]";
	}
////////////////////////////////////////////////////////////////////////////////
	@Override
	public double calcularDescuento() {
		return 0.20;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// GETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public String getEspecialidad() {
		return especialidad;
	}
////////////////////////////////////////////////////////////////////////////////
	public double getSalarioBase() {
		return salarioBase;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// SETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public void setEspecialidad(String especialidad) {
		this.especialidad = especialidad;
	}
////////////////////////////////////////////////////////////////////////////////
	public void setSalarioBase(double salarioBase) {
		this.salarioBase = salarioBase;
	}
}