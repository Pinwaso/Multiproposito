package Clase.Examenes.William;

public abstract class Usuario {
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////// VARIABLES ///////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private String id;
	private String nombre;
////////////////////////////////////////////////////////////////////////////////
///////////////////////////////// CONSTRUCTOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Constructor de Usuario
	 * @param id
	 * @param nombre
	 */
	public Usuario(String id, String nombre) {
		this.id = id;
		this.nombre = nombre;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// METODOS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método abstracto para mostrar la identificacion del Usuario
	 * @return
	 */
	public abstract String mostrarIdentificacion();
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método abstracto para calcular el descuento según el tipo
	 * @return
	 */
	public abstract double calcularDescuento();
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// GETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para obtener el id
	 * @return devuevle el id del Usuario
	 */
	public String getId() {
		return id;
	}
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para obtener el nombre
	 * @return devuelve el nombre del Usuario
	 */
	public String getNombre() {
		return nombre;
	}
}