package Clase.Examenes.William;

public class Clase {
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////// VARIABLES ///////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private NombreClase nombreCurso;
	private int horas;
	private NivelCurso nivel;
	private final double IVA = 0.21;
	private Profesor profesor;
////////////////////////////////////////////////////////////////////////////////
///////////////////////////////// CONSTRUCTOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public Clase(NombreClase nombreCurso, int horas, NivelCurso nivel, Profesor profesor) {
		this.setNombreCurso(nombreCurso);
		this.setHoras(horas);
		this.setNivel(nivel);
		this.setProfesor(profesor);
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// METODOS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public double calcularPrecioFinal() {
		NivelCurso curso = this.nivel;
		return curso.getFactorPrecio();
	}
////////////////////////////////////////////////////////////////////////////////
	public String mostrarInformacionGeneral() {
		return "Clase [nombreCurso=" + nombreCurso + ", horas=" + horas + ", nivel=" + nivel + ", IVA=" + IVA + "]";
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// GETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public NombreClase getNombreCurso() {
		return nombreCurso;
	}
////////////////////////////////////////////////////////////////////////////////
	public int getHoras() {
		return horas;
	}
////////////////////////////////////////////////////////////////////////////////
	public NivelCurso getNivel() {
		return nivel;
	}
////////////////////////////////////////////////////////////////////////////////
	public double getIVA() {
		return IVA;
	}
////////////////////////////////////////////////////////////////////////////////
	public void setProfesor(Profesor profesor) {
		this.profesor = profesor;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// SETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public void setNombreCurso(NombreClase nombreCurso) {
		this.nombreCurso = nombreCurso;
	}
////////////////////////////////////////////////////////////////////////////////
	public void setHoras(int horas) {
		this.horas = horas;
	}
////////////////////////////////////////////////////////////////////////////////
	public void setNivel(NivelCurso nivel) {
		this.nivel = nivel;
	}
////////////////////////////////////////////////////////////////////////////////
	public Profesor getProfesor() {
		return profesor;
	}	
}