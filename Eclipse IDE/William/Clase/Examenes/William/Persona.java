package Clase.Examenes.William;

public abstract class Persona extends Usuario {
////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////VARIABLES ///////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private int edad;
	private String dni;
////////////////////////////////////////////////////////////////////////////////
///////////////////////////////// CONSTRUCTOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////	
	/**
	 * Constructor de Persona
	 * @param id String id de la persona
	 * @param nombre String nombre de la persona
	 * @param edad int edad de la persona
	 * @param dni String dni de la persona
	 * @throws EdadInvalidaException lanza excepcion de edad invalida donde debe ser mayor a 0
	 */
	public Persona(String id, String nombre, int edad, String dni) throws EdadInvalidaException {
		super(id, nombre);
		this.setEdad(edad);
		this.setDni(dni);
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// METODOS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para mostrar los atributos de la clase
	 */
	@Override
	public String toString() {
		return "[id=" + super.getId() + ", nombre=" + super.getNombre() + ", edad=" + edad + ", dni=" + dni;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// GETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para obtener la edad
	 * @return
	 */
	public int getEdad() {
		return edad;
	}
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para obtener el DNI
	 * @return
	 */
	public String getDni() {
		return dni;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// SETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para establecer la edad
	 * @param edad int edad de la Persona
	 * @throws EdadInvalidaException lanza una excepcion donde la edad no debe ser menor a 0
	 */
	public void setEdad(int edad) throws EdadInvalidaException {
		if (edad < 0) {
			throw new EdadInvalidaException("La edad es invalida");
		} else {
			this.edad = edad;
		}
	}
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Método para establecer el dni de la Persona
	 * @param dni
	 */
	public void setDni(String dni) {
		this.dni = dni;
	}
}