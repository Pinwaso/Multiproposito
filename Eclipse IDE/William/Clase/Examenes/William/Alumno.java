package Clase.Examenes.William;

import java.util.ArrayList;
import java.util.HashMap;

public class Alumno extends Persona {
////////////////////////////////////////////////////////////////////////////////
////////////////////////////////// VARIABLES ///////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private int codigoAlumno;
	private double notaMedia;
	private HashMap<NombreClase, ArrayList<Double>> asignaturas = new HashMap<>();
////////////////////////////////////////////////////////////////////////////////
///////////////////////////////// CONSTRUCTOR //////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	/**
	 * Constructor para Alumno
	 * @param id String id del alumno
	 * @param nombre String nombre del alumno
	 * @param edad int edad del alumno
	 * @param dni
	 * @param codigoAlumno
	 * @param notaMedia
	 * @throws EdadInvalidaException lanza excepcion si la edad es menor a 0
	 * @throws NotaInvalidaException
	 */
	public Alumno(String id, String nombre, int edad, String dni, int codigoAlumno, double notaMedia)
			throws EdadInvalidaException, NotaInvalidaException {
		super(id, nombre, edad, dni);
		this.setCodigoAlumno(codigoAlumno);
		this.verificarNotaMedia(notaMedia);
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// METODOS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	private void verificarNotaMedia(double notaMedia) throws NotaInvalidaException {
		if (notaMedia >= 0 && notaMedia <= 10) {
			this.notaMedia = notaMedia;
		} else {
			throw new NotaInvalidaException("La nota media debe estar entre 0 y 10");
		}
	}
////////////////////////////////////////////////////////////////////////////////
	@Override
	public String mostrarIdentificacion() {
		return "Alumno " + super.toString() + ", codigoAlumno=" + codigoAlumno + ", notaMedia=" + notaMedia + "]";
	}
////////////////////////////////////////////////////////////////////////////////
	public boolean apto() {
		if (this.notaMedia >= 5.0) {
			return true;
		} else {
			return false;
		}
	}
////////////////////////////////////////////////////////////////////////////////
	@Override
	public double calcularDescuento() {
		double nota = this.notaMedia;
		if (nota >= 8.0) {
			return 0.1;
		} else if (nota >= 5) {
			return 0.05;
		} else {
			return 0.0;
		}
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// GETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public int getCodigoAlumno() {
		return codigoAlumno;
	}
////////////////////////////////////////////////////////////////////////////////
	public double getNotaMedia() {
		return notaMedia;
	}
////////////////////////////////////////////////////////////////////////////////
	public HashMap<NombreClase, ArrayList<Double>> getAsignaturas() {
		return asignaturas;
	}
////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////// SETTERS ////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////
	public void setNotaMedia(double notaMedia) {
		this.notaMedia = notaMedia;
	}
////////////////////////////////////////////////////////////////////////////////
	private void setCodigoAlumno(int codigoAlumno) {
		this.codigoAlumno = codigoAlumno;
	}
////////////////////////////////////////////////////////////////////////////////
	public void setAsignaturas(HashMap<NombreClase, ArrayList<Double>> asignaturas) {
		this.asignaturas = asignaturas;
	}
}