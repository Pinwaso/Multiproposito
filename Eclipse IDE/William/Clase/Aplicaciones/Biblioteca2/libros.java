package Clase.Aplicaciones.Biblioteca2;

public class libros extends publicacion implements prestable{
///////////////////////////////////////////////////////////////////
//////////////////////////// VARIABLES ////////////////////////////
///////////////////////////////////////////////////////////////////
	private boolean prestado;
///////////////////////////////////////////////////////////////////
/////////////////////////// CONSTRUCTOR ///////////////////////////
///////////////////////////////////////////////////////////////////	
	public libros(int codigo, int año, String titulo) {
		super(codigo, año, titulo);
		this.prestado = false;
	}
///////////////////////////////////////////////////////////////////
///////////////////////////// GETTERS /////////////////////////////
///////////////////////////////////////////////////////////////////
	public boolean getPrestado() {
		return this.prestado;
	}
///////////////////////////////////////////////////////////////////
///////////////////////////// SETTERS /////////////////////////////
///////////////////////////////////////////////////////////////////
	public void setPrestado(boolean prestado) {
		this.prestado = prestado;
	}
	@Override
	public String toString() {
		return "libros " + super.toString() + ", prestado=" + prestado + "]";
	}
///////////////////////////////////////////////////////////////////
	public void prestar() {
	}
///////////////////////////////////////////////////////////////////
	public void devolver() {
	}
///////////////////////////////////////////////////////////////////
	public void prestado() {
	}
}