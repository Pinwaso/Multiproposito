package Clase.Aplicaciones.Biblioteca2;

public class revistas extends publicacion {
///////////////////////////////////////////////////////////////////
//////////////////////////// VARIABLES ////////////////////////////
///////////////////////////////////////////////////////////////////
	private int numero;
///////////////////////////////////////////////////////////////////
/////////////////////////// CONSTRUCTOR ///////////////////////////
///////////////////////////////////////////////////////////////////	
	public revistas(int codigo, int año, String titulo, int numero) {
		super(codigo, año, titulo);
		setNumero(numero);
	}
///////////////////////////////////////////////////////////////////
///////////////////////////// GETTERS /////////////////////////////
///////////////////////////////////////////////////////////////////
	public int getNumero() {
		return this.numero;
	}
///////////////////////////////////////////////////////////////////
///////////////////////////// SETTERS /////////////////////////////
///////////////////////////////////////////////////////////////////
	public void setNumero(int numero) {
		this.numero = numero;
	}
///////////////////////////////////////////////////////////////////
///////////////////////////// MÉTODOS /////////////////////////////
///////////////////////////////////////////////////////////////////
	@Override
	public String toString() {
		return "revistas " + super.toString() + ", numero=" + numero + "]";
	}
}
